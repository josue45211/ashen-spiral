// Prints Docs/AUDIO_MANIFEST_0.24.md from the enemy cue table in ASEnemyRules.h, so the sound designer's list and the game's list can never disagree.
//   cl /std:c++17 /EHsc Tools\export_audio_manifest.cpp && export_audio_manifest.exe > Docs\AUDIO_MANIFEST_0.24.md
#include "../Source/AshenSpiral/Public/ASEnemyRules.h"
#include "../Source/AshenSpiral/Public/ASEnemyAbilities.h"
#include <cstdio>
#include <string>
using namespace ASEnemyRules;
static const char* AbilityName(int Id) {
    static const char* Names[]={"none","flier dive","flying boss molt","melee slash","archer shot","leaper pounce","bulwark charge","shaman blast","sniper shot","broodcaller summon","boss attack",
        "grunt shove","archer back-hop","duelist parry","duelist riposte","brute ground pound","brute enrage","leaper rift blink","leaper blink strike","shaman meteor rain",
        "frostbound elite glacial slam","burning elite cinder burst","shocking elite storm call","venomous elite seed bombs",
        "boss slam","boss marks","boss ring","boss charge","boss toll","boss seed bombs","boss blooms","boss roots","boss grasp","boss phase roar"};
    static_assert(sizeof(Names)/sizeof(Names[0])==AbilityCount,"every ability needs a name in the audio manifest");
    return Id>=0&&Id<AbilityCount?Names[Id]:"?";
}
// What each cue is for. Cues wired to an ability in the ability table say so; the rest belong to the 0.24 ability kits that are still being built.
static std::string When(int Cue) {
    std::string Out;
    for(int Id=1;Id<AbilityCount;++Id) {
        if(SpecFor(Id).CueWindup==Cue) Out+=std::string(Out.empty()?"":"; ")+"wind-up of "+AbilityName(Id);
        if(SpecFor(Id).CueRelease==Cue) Out+=std::string(Out.empty()?"":"; ")+"release of "+AbilityName(Id);
    }
    for(int M=MutationFrost;M<=MutationVenom;++M) if(Cue==MutationCue(M)) Out+=std::string(Out.empty()?"":"; ")+"an elite brute with this mutation appearing (played once when it first comes into view)";
    for(int Style=0;Style<HazardStyles;++Style) if(Cue==HazardArmCue(Style)) Out+=std::string(Out.empty()?"":"; ")+"a ground hazard arming (its warning is over)";
    if(Cue==CueGuardBreak) Out+=std::string(Out.empty()?"":"; ")+"a bulwark's guard being ripped open (played when the replicated guard-broken bit turns on)";
    if(Cue==CueSnipeLock) Out+=std::string(Out.empty()?"":"; ")+"the sniper's beam locking (played when it turns white-amber, 70% through the wind-up)";
    if(Cue==CueEggHatch) Out+=std::string(Out.empty()?"":"; ")+"a broodcaller's egg hatching into a minion (effect 19, size 1)";
    if(Cue==CueEggPop) Out+=std::string(Out.empty()?"":"; ")+"a hero popping a broodcaller's egg before it hatches (effect 19, size 0)";
    if(Cue==CuePackCall) Out+=std::string(Out.empty()?"":"; ")+"wind-up of a Gloomwing that is calling its pack (replaces its dive screech)";
    if(Cue==CueParryBlock) Out+=std::string(Out.empty()?"":"; ")+"a duelist's parry guard holding against a blow (played from the replicated block flag)";
    return Out.empty()?"an ability of the 0.24 kits (wired as each is built)":Out;
}
int main() {
    std::printf("# Ashen Spiral 0.24 - Enemy audio manifest\n\n");
    std::printf("Generated by `Tools/export_audio_manifest.cpp` from the cue table in `Source/AshenSpiral/Public/ASEnemyRules.h`. Do not edit by hand; change the table and regenerate.\n\n");
    std::printf("Every enemy telegraph and every attack release has a **cue**. The game plays a cue from the replicated enemy state on every machine, at a volume that falls with\n");
    std::printf("distance to the local player (full inside 6 m, silent beyond 32 m). Each cue names a file below. **Until that file exists the game plays the existing sound in the last\n");
    std::printf("column at the listed pitch and volume**, so nothing is silent and nothing breaks while the real files are made.\n\n");
    std::printf("## How to deliver a file\n\n");
    std::printf("1. WAV, **mono, 16-bit PCM, 44.1 kHz** (`Tests/run_tests.py` rejects anything else), named exactly like the **File** column.\n");
    std::printf("2. Put it in `SourceArt/Audio/`. Nothing else needs editing: the importer takes every WAV in that folder and the test counts follow the folder.\n");
    std::printf("3. Run `Reimport_Source_Art.bat` (or `Setup_and_Open.bat`). The cue starts using the new file on the next launch, at its natural pitch and the listed volume.\n");
    std::printf("4. Level: peak near -3 dBFS, about as loud as the existing cues (the volume column is a multiplier applied on top). No leading silence; tails under half a second\n");
    std::printf("   unless the note says otherwise. A wind-up cue should be shorter than its wind-up so it ends as the attack lands.\n\n");
    std::printf("Telegraph and release cues together are the readability rule of this update: a player should be able to tell what is coming with their eyes closed. See\n");
    std::printf("`Docs/TELEGRAPH_LANGUAGE_0.24.md`.\n\n");
    std::printf("## Cues (%d)\n\n", CueCount-1);
    std::printf("| # | File | Plays at | What it should sound like | Until delivered |\n|---|---|---|---|---|\n");
    for(int Id=1;Id<CueCount;++Id) {
        const CueSpec& C=CueFor(Id);
        char Fallback[96];
        if(C.Fallback[0]) std::snprintf(Fallback,sizeof(Fallback),"`%s.wav` x%.2f volume, pitch %.2f",C.Fallback,C.Volume,C.Pitch);
        else std::snprintf(Fallback,sizeof(Fallback),"silent (the swing arc keeps playing `S_Attack` until this is delivered)");
        std::printf("| %d | `%s.wav` | %s | %s | %s |\n",Id,C.Stem,When(Id).c_str(),C.Note,Fallback);
    }
    std::printf("\n## Existing sounds the fallbacks use\n\n`S_Attack`, `S_Collapse`, `S_Dash`, `S_HammerHit`, `S_HammerLeap`, `S_HammerSmash`, `S_HammerSwing`, `S_Hit`, `S_Reward`, `S_Spiral` (all in `SourceArt/Audio/`).\n");
    return 0;
}
