"""Generate SourceArt/Meshes/SM_SwingArc.obj (0.24): the frontal crescent drawn for each Blade/Scythe swing.
Pure Python, no dependencies (the older generators need numpy + trimesh). Output is deterministic; running it twice changes nothing.

Shape: a flat crescent in the XY plane, opening toward +X (the swing's forward). The OUTER edge is a circle of radius 50 cm, so a runtime scale of
Reach/50 puts the outer edge exactly at the swing's reach. It spans +-92.5 degrees, matching the swing's real hit half-plane (dot(forward, to-target) > -0.05).
The width tapers to a point at both ends so it reads as a slash rather than a ring.
"""
from pathlib import Path
import json
import math

ROOT = Path(__file__).resolve().parents[1] / 'SourceArt'
NAME = 'SM_SwingArc'
OUTER = 50.0
HALF_ANGLE = math.radians(92.5)
MAX_WIDTH = 7.5      # cm at the middle of the crescent
MIN_WIDTH = 0.8      # cm at the tips (non-zero so every triangle has area)
HALF_THICK = 1.6     # cm above and below the plane
STATIONS = 60


def width(theta):
    taper = math.cos(0.5 * math.pi * abs(theta) / HALF_ANGLE) ** 0.7
    return MIN_WIDTH + (MAX_WIDTH - MIN_WIDTH) * taper


def build():
    stations = []
    for i in range(STATIONS + 1):
        theta = -HALF_ANGLE + 2.0 * HALF_ANGLE * i / STATIONS
        inner = OUTER - width(theta)
        c, s = math.cos(theta), math.sin(theta)
        stations.append({
            'theta': theta,
            'ot': (OUTER * c, OUTER * s, HALF_THICK), 'it': (inner * c, inner * s, HALF_THICK),
            'ob': (OUTER * c, OUTER * s, -HALF_THICK), 'ib': (inner * c, inner * s, -HALF_THICK),
        })
    quads = []  # (a, b, c, d, expected outward normal direction function)
    for i in range(STATIONS):
        a, b = stations[i], stations[i + 1]
        mid = 0.5 * (a['theta'] + b['theta'])
        radial = (math.cos(mid), math.sin(mid), 0.0)
        quads.append(((a['ot'], a['it'], b['it'], b['ot']), (0.0, 0.0, 1.0)))
        quads.append(((a['ob'], b['ob'], b['ib'], a['ib']), (0.0, 0.0, -1.0)))
        quads.append(((a['ot'], b['ot'], b['ob'], a['ob']), radial))
        quads.append(((a['it'], a['ib'], b['ib'], b['it']), (-radial[0], -radial[1], 0.0)))
    for end, sign in ((stations[0], -1.0), (stations[-1], 1.0)):
        th = end['theta']
        tangent = (-math.sin(th) * sign, math.cos(th) * sign, 0.0)  # points away from the crescent along its length
        quads.append(((end['ot'], end['it'], end['ib'], end['ob']), tangent))
    return quads


def sub(a, b): return (a[0] - b[0], a[1] - b[1], a[2] - b[2])
def cross(a, b): return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])
def dot(a, b): return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]
def norm(a):
    n = math.sqrt(dot(a, a))
    return (a[0] / n, a[1] / n, a[2] / n)


def triangles():
    tris = []
    for quad, want in build():
        p = [tuple(round(v, 8) for v in pt) for pt in quad]
        for tri in ((p[0], p[1], p[2]), (p[0], p[2], p[3])):
            n = cross(sub(tri[1], tri[0]), sub(tri[2], tri[0]))
            if dot(n, n) < 1e-9:
                continue  # collapsed sliver at a tip: skip rather than emit a zero-area triangle
            if dot(n, want) < 0:
                tri = (tri[0], tri[2], tri[1])  # flip winding so the normal faces outward
            tris.append(tri)
    return tris


def write(tris):
    lines = ['# generated by Tools/generate_swing_arc.py', 'mtllib material.mtl', 'usemtl material_0']
    verts, uvs, normals, faces = [], [], [], []
    for tri in tris:
        n = norm(cross(sub(tri[1], tri[0]), sub(tri[2], tri[0])))
        base = len(verts)
        for pt in tri:
            verts.append(pt)
            uvs.append((pt[0] / 100.0, pt[1] / 100.0))
            normals.append(n)
        faces.append((base + 1, base + 2, base + 3))
    lines += ['v %.8f %.8f %.8f' % v for v in verts]
    lines += ['vt %.8f %.8f' % t for t in uvs]
    lines += ['vn %.8f %.8f %.8f' % n for n in normals]
    lines += ['f %d/%d/%d %d/%d/%d %d/%d/%d' % (a, a, a, b, b, b, c, c, c) for a, b, c in faces]
    (ROOT / 'Meshes').mkdir(parents=True, exist_ok=True)
    (ROOT / 'Meshes' / (NAME + '.obj')).write_text('\n'.join(lines) + '\n', encoding='ascii')
    mins = [min(v[i] for v in verts) for i in range(3)]
    maxs = [max(v[i] for v in verts) for i in range(3)]
    return {'min': mins, 'max': maxs, 'extent': [maxs[i] - mins[i] for i in range(3)]}, len(faces)


def main():
    bounds_path = ROOT / 'mesh_bounds.json'
    bounds = json.loads(bounds_path.read_text()) if bounds_path.exists() else {}
    entry, count = write(triangles())
    bounds[NAME] = entry
    bounds_path.write_text(json.dumps(bounds, indent=2) + '\n')
    print('%s: %d triangles, extent %s' % (NAME, count, [round(x, 3) for x in entry['extent']]))


if __name__ == '__main__':
    main()
